CREATE TABLE IF NOT EXISTS `workflow_approval_results` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '本地流程结果记录 ID',
  `business_key` varchar(160) NOT NULL DEFAULT '' COMMENT '业务单号，IC 审版=approval_no',
  `owner_system` varchar(60) NOT NULL DEFAULT '' COMMENT '来源系统，如 ic',
  `process_code` varchar(120) NOT NULL DEFAULT '' COMMENT 'Workflow 流程 code',
  `requested_process_version` int unsigned NOT NULL DEFAULT 0 COMMENT '调用方指定的流程版本，0 表示未指定',
  `process_version` int unsigned NOT NULL DEFAULT 0 COMMENT 'Workflow 实际流程版本',
  `start_status` varchar(30) NOT NULL DEFAULT 'pending' COMMENT '发起状态：pending/processing/succeeded/failed',
  `instance_uuid` varchar(64) NOT NULL DEFAULT '' COMMENT 'Workflow 实例 UUID',
  `workflow_status` varchar(30) NOT NULL DEFAULT 'not_started' COMMENT 'not_started/running/waiting/approved/rejected/failed/cancelled',
  `start_error` varchar(1000) NOT NULL DEFAULT '' COMMENT '发起失败原因',
  `start_attempts` int unsigned NOT NULL DEFAULT 0 COMMENT '流程发起尝试次数',
  `start_next_retry_at` datetime NULL DEFAULT NULL COMMENT '流程发起下次重试时间，无重试计划时为 NULL',
  `start_processing_at` datetime NULL DEFAULT NULL COMMENT '流程发起任务抢占时间，未处理时为 NULL',
  `result` varchar(30) NOT NULL DEFAULT '' COMMENT '终态 approved/rejected',
  `result_value` varchar(60) NOT NULL DEFAULT '' COMMENT '流程 result_mapping 映射值',
  `idempotency_key` varchar(190) NOT NULL DEFAULT '' COMMENT '1.0 兼容幂等键，新代码不再用于回调审计',
  `start_idempotency_key` varchar(64) NOT NULL DEFAULT '' COMMENT '发起幂等键 SHA-256',
  `delivery_id` varchar(80) NOT NULL DEFAULT '' COMMENT 'Workflow 投递 ID',
  `callback_payload_json` mediumtext NULL COMMENT '原始回调 JSON',
  `business_payload_json` mediumtext NULL COMMENT '发起时 business_payload',
  `input_json` mediumtext NULL COMMENT '发起时 input',
  `local_apply_status` varchar(40) NOT NULL DEFAULT 'pending' COMMENT 'pending/processing/applied/skipped/failed',
  `local_apply_error` varchar(1000) NOT NULL DEFAULT '' COMMENT '映射失败原因',
  `apply_attempts` int unsigned NOT NULL DEFAULT 0 COMMENT '业务结果应用尝试次数',
  `apply_next_retry_at` datetime NULL DEFAULT NULL COMMENT '业务结果应用下次重试时间，无重试计划时为 NULL',
  `apply_processing_at` datetime NULL DEFAULT NULL COMMENT '业务结果应用任务抢占时间，未处理时为 NULL',
  `started_at` datetime NULL DEFAULT NULL COMMENT 'Workflow 实例开始时间，未开始时为 NULL',
  `finished_at` datetime NULL DEFAULT NULL COMMENT 'Workflow 实例结束时间，未结束时为 NULL',
  `applied_at` datetime NULL DEFAULT NULL COMMENT '业务结果应用完成时间，未完成时为 NULL',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_war_idem` (`idempotency_key`),
  UNIQUE KEY `uk_war_biz` (`business_key`,`process_code`,`owner_system`),
  KEY `idx_war_route_apply_due` (`process_code`,`owner_system`,`local_apply_status`,`workflow_status`,`apply_next_retry_at`),
  KEY `idx_war_route_apply_lease` (`process_code`,`owner_system`,`local_apply_status`,`apply_processing_at`),
  KEY `idx_war_route_start_due` (`process_code`,`owner_system`,`start_status`,`start_next_retry_at`),
  KEY `idx_war_route_start_lease` (`process_code`,`owner_system`,`start_status`,`start_processing_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Workflow 审核桥接结果表';

CREATE TABLE IF NOT EXISTS `workflow_callback_deliveries` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '回调投递记录 ID',
  `approval_result_id` bigint unsigned NOT NULL DEFAULT 0 COMMENT '本地流程结果记录 ID',
  `business_key` varchar(160) NOT NULL DEFAULT '' COMMENT '业务单号快照',
  `owner_system` varchar(60) NOT NULL DEFAULT '' COMMENT '来源系统快照',
  `process_code` varchar(120) NOT NULL DEFAULT '' COMMENT 'Workflow 流程 code 快照',
  `instance_uuid` varchar(64) NOT NULL DEFAULT '' COMMENT 'Workflow 实例 UUID 快照',
  `event` varchar(60) NOT NULL DEFAULT '' COMMENT '回调事件名称',
  `result` varchar(30) NOT NULL DEFAULT '' COMMENT '回调审批结果',
  `result_value` varchar(60) NOT NULL DEFAULT '' COMMENT '回调结果映射值',
  `idempotency_key` varchar(190) NOT NULL DEFAULT '' COMMENT 'Workflow 回调幂等键',
  `delivery_id` varchar(80) NOT NULL DEFAULT '' COMMENT 'Workflow 投递 ID',
  `payload_json` mediumtext NULL COMMENT '原始回调 JSON，应用层默认空对象',
  `received_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '回调接收时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_wcd_idempotency` (`idempotency_key`),
  KEY `idx_wcd_result` (`approval_result_id`),
  KEY `idx_wcd_instance` (`instance_uuid`),
  KEY `idx_wcd_received` (`received_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Workflow 回调投递记录';
